export type WordOfTheDay = {
  word: string;
  status: VocabularyStatus;
  translation: string | null;
  definition: string | null;
  hasAiInsights: boolean;
};

/**
 * Deterministic per student per calendar day — no OpenAI call here, ever
 * (a dashboard widget must never add AI latency to the page load). Picks
 * from the student's own real saved words only; shows whatever real data
 * already exists, honestly null/absent if this word has never been
 * AI-explored yet, rather than fabricating anything.
 */
export async function getWordOfTheDay(studentId: string): Promise<WordOfTheDay | null> {
  const total = await prisma.studentVocabulary.count({ where: { studentId } });
  if (total === 0) return null;

  const dayIndex = Math.floor(Date.now() / 86_400_000);
  const skip = dayIndex % total;

  const [row] = await prisma.studentVocabulary.findMany({
    where: { studentId },
    orderBy: { addedAt: "asc" },
    skip,
    take: 1,
    include: { vocabularyWord: true },
  });
  if (!row) return null;

  return {
    word: row.vocabularyWord.word,
    status: row.status,
    translation: row.vocabularyWord.uzbekTranslation,
    definition: row.vocabularyWord.englishDefinition,
    hasAiInsights: row.vocabularyWord.aiGeneratedAt != null,
  };
}
