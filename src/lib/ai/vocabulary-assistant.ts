export type VocabularyAiHistoryWord = { word: string; at: Date; cached: boolean };

/** Most-recent-first, deduplicated by word — "last viewed" and "recently explained" each mean one row per word, not one per click. */
function dedupeByWord<T extends { vocabularyWord: { word: string } | null; createdAt: Date; servedFromCache: boolean }>(
  rows: T[],
  limit: number
): VocabularyAiHistoryWord[] {
  const seen = new Set<string>();
  const result: VocabularyAiHistoryWord[] = [];
  for (const row of rows) {
    const word = row.vocabularyWord?.word;
    if (!word || seen.has(word)) continue;
    seen.add(word);
    result.push({ word, at: row.createdAt, cached: row.servedFromCache });
    if (result.length >= limit) break;
  }
  return result;
}

export type VocabularyAiActivityRow = {
  id: string;
  word: string | null;
  action: "WORD_INTELLIGENCE" | "EXPLAIN_WORD";
  cached: boolean;
  at: Date;
};

export type VocabularyAiHistory = {
  lastViewed: VocabularyAiHistoryWord[];
  recentlyExplained: VocabularyAiHistoryWord[];
  activity: VocabularyAiActivityRow[];
};

/** Every list here is a real query against VocabularyAiActionLog — no placeholder rows. */
export async function getVocabularyAiHistory(studentId: string, limit = 10): Promise<VocabularyAiHistory> {
  const [viewedRows, explainedRows, activityRows] = await Promise.all([
    prisma.vocabularyAiActionLog.findMany({
      where: { studentId, action: "WORD_INTELLIGENCE" },
      orderBy: { createdAt: "desc" },
      take: limit * 4, // enough raw rows to dedupe down to `limit` distinct words
      include: { vocabularyWord: { select: { word: true } } },
    }),
    prisma.vocabularyAiActionLog.findMany({
      where: { studentId, action: "EXPLAIN_WORD" },
      orderBy: { createdAt: "desc" },
      take: limit * 4,
      include: { vocabularyWord: { select: { word: true } } },
    }),
    prisma.vocabularyAiActionLog.findMany({
      where: { studentId },
      orderBy: { createdAt: "desc" },
      take: 30,
      include: { vocabularyWord: { select: { word: true } } },
    }),
  ]);

  return {
    lastViewed: dedupeByWord(viewedRows, limit),
    recentlyExplained: dedupeByWord(explainedRows, limit),
    activity: activityRows.map((row) => ({
      id: row.id,
      word: row.vocabularyWord?.word ?? null,
      action: row.action,
      cached: row.servedFromCache,
      at: row.createdAt,
    })),
  };
}

